"""Reliability check for the evaluation sets: python scripts/audit.py [--out review.md] name=predictions_file ...

    python scripts/audit.py lora=runs/<1.7b dir>/predictions.jsonl shot4=runs/baseline-1.7b/predictions_shots4.jsonl \\
        zero=runs/baseline-1.7b/predictions.jsonl small=runs/<0.6b dir>/predictions.jsonl

It does three things:
  1. Accuracy and a 95% confidence interval (2000 bootstrap samples) for every evaluation set and model, next to
     two no-skill baselines: chance (mean of 1 / option count) and "always answer the most common letter". When the
     lower bound of a model's interval does not beat the baselines, the number says nothing about ability.
  2. Paired per-item differences between every two models (counts of items one got right and the other wrong, and
     z); differences with |z| < 2 are not interpreted.
  3. Suspicious items: items where most models agree on the same "wrong" answer. Either the item is hard or the
     label is questionable. For the self-built sets the text is listed in a Markdown review table (--out), to be
     judged one by one as "label correct / label wrong / ambiguous".
"""

from __future__ import annotations

import collections
import itertools
import json
import math
import random
import sys
from pathlib import Path

LETTERS = "ABCDEFGHIJKLMNOP"


def load(path):
    return [json.loads(l) for l in open(path, encoding="utf-8") if l.strip()]


def ci(hits: list[bool], n_boot: int = 2000, seed: int = 0):
    rng = random.Random(seed)
    n = len(hits)
    means = sorted(sum(hits[rng.randrange(n)] for _ in range(n)) / n for _ in range(n_boot))
    return sum(hits) / n, means[int(0.025 * n_boot)], means[int(0.975 * n_boot)]


def main(argv: list[str]) -> None:
    out_path = None
    if "--out" in argv:
        i = argv.index("--out"); out_path = argv[i + 1]; argv = argv[:i] + argv[i + 2:]
    data_dir = "data"
    if "--data" in argv:
        i = argv.index("--data"); data_dir = argv[i + 1]; argv = argv[:i] + argv[i + 2:]
    runs = dict(a.split("=", 1) for a in argv)
    if not runs:
        sys.exit(__doc__)
    preds = {name: collections.defaultdict(dict) for name in runs}
    for name, path in runs.items():
        for p in load(path):
            preds[name][p["dataset"]][p["id"]] = p
    datasets = [d for d in next(iter(preds.values())) if all(d in preds[m] for m in runs)]
    names = list(runs)

    print("## 1. Accuracy, 95% interval and baselines\n")
    print("| set | n | chance | always the same letter | " + " | ".join(names) + " |")
    print("| --- | --- | --- | --- | " + " | ".join("---" for _ in names) + " |")
    for d in datasets:
        ref = list(preds[names[0]][d].values())
        chance = sum(1 / p["n"] for p in ref) / len(ref)
        major = max(collections.Counter(p["label"] for p in ref).values()) / len(ref)
        cells = []
        for m in names:
            acc, lo, hi = ci([p["pred"] == p["label"] for p in preds[m][d].values()])
            flag = "" if lo > max(chance, major) else " ⚠"
            cells.append(f"{acc:.3f} [{lo:.2f}, {hi:.2f}]{flag}")
        print(f"| {d} | {len(ref)} | {chance:.2f} | {major:.2f} | " + " | ".join(cells) + " |")
    print("\n⚠ = the lower bound of the interval does not exceed the higher of the two baselines.\n")

    print("## 2. Paired per-item comparison (a difference needs |z| ≥ 2)\n")
    print("| set | comparison | first right, second wrong | first wrong, second right | z |\n| --- | --- | --- | --- | --- |")
    for d in datasets:
        for a, b in itertools.combinations(names, 2):
            ids = preds[a][d].keys() & preds[b][d].keys()
            w = sum(preds[a][d][i]["pred"] == preds[a][d][i]["label"] and preds[b][d][i]["pred"] != preds[b][d][i]["label"] for i in ids)
            l = sum(preds[a][d][i]["pred"] != preds[a][d][i]["label"] and preds[b][d][i]["pred"] == preds[b][d][i]["label"] for i in ids)
            z = (w - l) / math.sqrt(w + l) if w + l else 0.0
            print(f"| {d} | {a} vs {b} | {w} | {l} | {z:+.1f}{' **' if abs(z) >= 2 else ''} |")

    print("\n## 3. Suspicious items (most models agree on the same non-label answer)\n")
    review = ["# Evaluation set review list", "",
              "Generated by `scripts/audit.py`. It lists the items where **most models agree on the same non-label answer**: either the item is hard, or the label is wrong or ambiguous.",
              "Read each one and fill in the verdict column: `label correct` / `label wrong` / `ambiguous`. Fix wrong labels in `evalsets/*/items.jsonl`; delete or rewrite ambiguous items.", ""]
    need = max(2, math.ceil(len(names) * 0.75))
    for d in datasets:
        test = Path(data_dir) / f"test_{d}.jsonl"
        rows = {r["id"]: r for r in load(test)} if test.exists() else {}
        sus = []
        for i, p in preds[names[0]][d].items():
            votes = collections.Counter(preds[m][d][i]["pred"] for m in names if i in preds[m][d])
            top, cnt = votes.most_common(1)[0]
            if top != p["label"] and cnt >= need:
                sus.append((i, p["label"], top, cnt))
        print(f"- {d}: {len(sus)} / {len(preds[names[0]][d])} items")
        if not sus or not rows or not d.startswith("ja_"):      # the review table only lists self-built sets; labels of public sets are not ours to change
            continue
        review += [f"## {d} ({len(sus)} / {len(rows)} items)", "", "| id | text | question | label | model majority | verdict |", "| --- | --- | --- | --- | --- | --- |"]
        for i, gold, top, cnt in sorted(sus):
            r = rows.get(i)
            if not r:
                continue
            opt = lambda L: r["options"][LETTERS.index(L)][0]
            state = r["state"].replace("|", "｜")
            state = state if len(state) <= 120 else state[:120] + "…"
            review.append(f"| {i[:40]} | {state} | {r['question']} | {opt(gold)} | {opt(top)} ({cnt}/{len(names)}) | |")
        review.append("")
    if out_path:
        Path(out_path).write_text("\n".join(review) + "\n", encoding="utf-8")
        print(f"\nreview list written to {out_path}")


if __name__ == "__main__":
    main(sys.argv[1:])
