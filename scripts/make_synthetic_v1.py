# ---------- validate, deduplicate against the evaluation sets, write the file ----------
def grams(s: str) -> set[str]:
    s = "".join(s.split())
    return {s[i:i + 3] for i in range(max(1, len(s) - 2))}


eval_states = []
for f in (ROOT / "evalsets").glob("*/items.jsonl"):
    eval_states += [json.loads(l)["state"] for l in open(f, encoding="utf-8") if l.strip()]
eval_grams = [(s, grams(s)) for s in eval_states]
kept, dropped, seen = [], [], set()
for it in items:
    key = (it["state"], it["question"])
    assert 2 <= len(it["options"]) <= 16 and 0 <= it["answer"] < len(it["options"]) and "\n" not in it["state"], it
    if key in seen:
        dropped.append(("duplicate", it["state"])); continue
    seen.add(key)
    g = grams(it["state"])
    near = next((s for s, eg in eval_grams if s == it["state"] or (len(g) >= 6 and len(g & eg) / len(g | eg) >= 0.6)), None)
    if near is not None:
        dropped.append(("close to an evaluation item", f"{it['state']}  ≈  {near}")); continue
    kept.append(it)

out = ROOT / "datasets" / "synthetic" / "train.jsonl"
out.parent.mkdir(parents=True, exist_ok=True)
with open(out, "w", encoding="utf-8") as f:
    for it in kept:
        f.write(json.dumps(it, ensure_ascii=False) + "\n")

