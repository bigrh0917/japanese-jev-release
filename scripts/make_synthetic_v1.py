"""Generate datasets/synthetic/train.jsonl (v1, about 1,100 items): kinds of Japanese decision items missing from public data.

    python scripts/make_synthetic_v1.py

Provenance: the sentences, templates and labels were written by Claude (Anthropic's LLM).
The evaluation sets (evalsets/) were also written by Claude, so training and evaluation items share an author,
and part of the gain on those sets may come from learning the same labeling conventions. The script guarantees
that no sentence is shared (see the deduplication at the end), but a more reliable check needs new items written
by people.

Design:
  negation                    肯定 / 単純否定 / 二重否定 / 否定の結論 in groups (minimal pairs), half yes and half no
  litotes with adjectives     「悪くない」 -> positive; grouped with 「悪い」「良くない」「いい」
  negative questions          「〜ないんですか？」 answered 「はい」 -> no; paired with the positive question
  indirect replies            承諾 / 断り / 保留 / 条件付き承諾, a quarter each
  replies to offers           「大丈夫です / 結構です / いいです」: to an offer = not needed; to a check = no problem; half each
  honorifics and relationship six relationships, 20 items each
  scales (score)              約束の実現度, 確信度, 緊急度, 不満の強さ, 感情の強さ; the last two are deliberately dominated by the lowest level
  idioms                      figurative vs literal meaning
"""

